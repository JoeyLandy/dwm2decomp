    inc hl
    inc hl
    inc hl
    inc hl
    call CountBit0MatchOfEAndHL
    inc hl
    inc hl
    call CountBit0MatchOfEAndHL
    inc hl
    inc hl
    call CountBit0MatchOfEAndHL
    inc hl
    inc hl
    call CountBit0MatchOfEAndHL
    inc hl
    inc hl
    call CountBit0MatchOfEAndHL
    inc hl
    inc hl
    call CountBit0MatchOfEAndHL
    ld a, l
    add $96
    ld l, a
    ld a, h
    adc $ff
    ld h, a
    push bc
    ld b, $0a
    ld d, $00

.loop:
    ld a, [hli]
    cp $f0
    jr z, .restore
    cp $8d
    jr z, .next
    cp $8e
    jr z, .next
    inc d

.next:
