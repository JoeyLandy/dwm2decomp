    ld c, MON_ITEM
    call SRAMRecordAddress
    ld bc, $0000
    ld a, [hl]
    cp $1d
    jr c, .set_growth_temp0_to_FF
    cp $23
    jr c, .set_growth_temp0

.set_growth_temp0_to_FF:
