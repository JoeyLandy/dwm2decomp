; The damage estimate for wBattleActionId from its 17-byte record (the table at $40D4): the word at
; offset 9 for the player's side (and in link mode 1), 13 for foes, two bytes further when the
; actor's AI mode is 4. (C2, E-0357; probed E-0379)
ComputeDamageEstimateForAction_FromSkillRecord::
    ld a, [wBattleActionId]
    ld c, a
    ld b, $00
    ld a, $11
    call Multiply8By16
    ld a, l
    add $d4
    ld l, a
    ld a, h
    adc $40
    ld h, a
    ld bc, $0009
    ld a, [wLinkMode]
    cp $01
    jr z, .read_battle_actor
    ld a, [wBattleActor]
    cp $04
    jr c, .read_battle_actor
    ld bc, $000d

.read_battle_actor:
    add hl, bc
    ld a, [wBattleActor]
    push hl
    ld hl, wSlotAIMode
    add_a_to_hl
    ld a, [hl]
    pop hl
    cp $04
    jr nz, .set_battle_damage_lo
    inc hl
    inc hl

.set_battle_damage_lo:
    ld a, [hli]
    ld [wBattleDamageLo], a
    ld a, [hl]
    ld [wBattleDamageHi], a
    ret

