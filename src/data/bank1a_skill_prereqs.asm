    push hl
    ld b, $00
    ld a, [hli]
    ld d, [hl]
    ld e, a
    ld hl, -999
    add hl, de
    ld a, h
    or l
    jr z, .skip
    ld e, l
    add hl, bc
    ld a, h
    or l
    jr z, .done
    bit 7, h
    jr nz, .done
    xor a
    sub e
    ld c, a
    jr .done

.skip:
    ld c, $00

.done:
    ld a, c
    pop hl
    ret

