; wRecordBuffer/wRecordBuffer + $1 (the first word of the record buffer) = skill number: copies the
; 17-byte record at SkillTable + 17 * number (bank $1A, $40D4) to wRecordBufferData
LoadSkillRecord::
    ld a, [wRecordBuffer]
    ld c, a
    ld a, [wRecordBuffer + $1]
    ld b, a
    ld a, $11
    call Multiply8By16
    ld a, l
    add $d4
    ld l, a
    ld a, h
    adc $40
    ld h, a
    ld de, wRecordBufferData
    ld b, $11

.loop:
    ld a, [hli]
    ld [de], a
    inc de
    dec b
    jr nz, .loop
    ret

